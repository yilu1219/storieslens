  const originalText = new WeakMap();
  const originalAttributes = new WeakMap();

  const normalizeLocale = (value) => value === "zh" ? "zh" : "en";
  let locale = normalizeLocale(localStorage.getItem(STORAGE_KEY));

  const translate = (text, targetLocale = locale) => targetLocale === "zh" ? (zh[text] || text) : text;

  const translateTextNodes = () => {
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        if (!node.parentElement || ["SCRIPT", "STYLE"].includes(node.parentElement.tagName)) return NodeFilter.FILTER_REJECT;
        return node.nodeValue.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
      }
    });
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach((node) => {
      if (!originalText.has(node)) originalText.set(node, node.nodeValue.trim());
      const source = originalText.get(node);
      const leading = node.nodeValue.match(/^\s*/)?.[0] || "";
      const trailing = node.nodeValue.match(/\s*$/)?.[0] || "";
      node.nodeValue = `${leading}${translate(source)}${trailing}`;
    });
  };

  const translateAttributes = () => {
    document.querySelectorAll("[placeholder], [aria-label]").forEach((element) => {
      if (!originalAttributes.has(element)) {
        originalAttributes.set(element, {
          placeholder: element.getAttribute("placeholder"),
          ariaLabel: element.getAttribute("aria-label")
        });
      }
      const source = originalAttributes.get(element);
      if (source.placeholder) element.setAttribute("placeholder", translate(source.placeholder));
      if (source.ariaLabel) element.setAttribute("aria-label", translate(source.ariaLabel));
    });
  };

  const updateMetadata = () => {
    const isStart = document.body.classList.contains("start-page");
    const isStudio = window.location.pathname.endsWith("visual-write.html");
    const isDna = window.location.pathname.endsWith("story-dna.html");
    const isGroup = window.location.pathname.endsWith("group-project-studio.html");
    const isPremiere = window.location.pathname.endsWith("solo-premiere.html");
    const isCheckout = window.location.pathname.endsWith("checkout.html");
    const isTeacher = window.location.pathname.endsWith("teacher-dashboard.html");
    const isArchive = window.location.pathname.endsWith("classroom-archive.html");
    const isLessonBuilder = window.location.pathname.endsWith("create-reading-project.html");
    const isLessonReview = window.location.pathname.endsWith("create-reading-review.html");
    const isLessonAssign = window.location.pathname.endsWith("create-reading-assign.html");
    const isLessonPublish = window.location.pathname.endsWith("create-reading-publish.html");
    if (locale === "zh") document.title = isStart ? "开始创作｜语镜故事 StoriesLens" : isStudio ? "故事创作室｜语镜故事 StoriesLens" : isDna ? "发现你的 Story DNA｜语镜故事 StoriesLens" : isGroup ? "小队共创工作室｜语镜故事 StoriesLens" : isPremiere ? "我的故事首映｜语镜故事 StoriesLens" : isCheckout ? "创作者结账｜语镜故事 StoriesLens" : isTeacher ? "作品墙出版｜语镜故事 StoriesLens" : isArchive ? "作品墙变成班级书｜语镜故事 StoriesLens" : isLessonBuilder ? "创建读写结合课｜语镜故事 StoriesLens" : isLessonReview ? "审核读写课｜语镜故事 StoriesLens" : isLessonAssign ? "分配创作任务｜语镜故事 StoriesLens" : isLessonPublish ? "发布班级项目｜语镜故事 StoriesLens" : "语镜故事 StoriesLens｜把灵感变成原创故事";
    else document.title = isStart ? "Start Creating | StoriesLens" : isStudio ? "Story Studio | StoriesLens" : isDna ? "Discover Your Story DNA | StoriesLens" : isGroup ? "Group Project Studio | StoriesLens" : isPremiere ? "My Story Premiere | StoriesLens" : isCheckout ? "Creator Checkout | StoriesLens" : isTeacher ? "Bulletin Board Publisher | StoriesLens" : isArchive ? "Bulletin Board to Book | StoriesLens" : isLessonBuilder ? "Create a Reading-to-Writing Lesson | StoriesLens" : isLessonReview ? "Review Lesson | StoriesLens" : isLessonAssign ? "Assign Lesson | StoriesLens" : isLessonPublish ? "Publish Lesson | StoriesLens" : "StoriesLens | Create a Story Together";
  };

  const applyLocale = (nextLocale, emit = true) => {
    locale = normalizeLocale(nextLocale);
    localStorage.setItem(STORAGE_KEY, locale);
    document.documentElement.lang = locale === "zh" ? "zh-CN" : "en";
    translateTextNodes();
    translateAttributes();
    updateMetadata();
    document.querySelectorAll("[data-locale]").forEach((button) => {
      const active = button.dataset.locale === locale;
      button.classList.toggle("is-active", active);
      button.setAttribute("aria-pressed", String(active));
    });
    if (emit) window.dispatchEvent(new CustomEvent("storieslens:locale", { detail: { locale } }));
  };

  document.querySelectorAll("[data-locale]").forEach((button) => {
    button.addEventListener("click", () => applyLocale(button.dataset.locale));
  });

